package utils;

/** Deteccao do tipo real de imagem pelos primeiros bytes (nao confia no Content-Type enviado pelo cliente). */
public final class ImageType {

    /** Tamanho maximo aceito para a imagem de um produto (2 MB). */
    public static final int MAX_BYTES = 2 * 1024 * 1024;

    private ImageType() {
    }

    /** Retorna o tipo MIME (jpeg, png, gif ou webp) ou null se os bytes nao forem uma imagem aceita. */
    public static String detect(byte[] b) {
        if (b == null || b.length < 12) {
            return null;
        }
        if ((b[0] & 0xFF) == 0xFF && (b[1] & 0xFF) == 0xD8 && (b[2] & 0xFF) == 0xFF) {
            return "image/jpeg";
        }
        if ((b[0] & 0xFF) == 0x89 && b[1] == 'P' && b[2] == 'N' && b[3] == 'G'
                && b[4] == 0x0D && b[5] == 0x0A && b[6] == 0x1A && b[7] == 0x0A) {
            return "image/png";
        }
        if (b[0] == 'G' && b[1] == 'I' && b[2] == 'F' && b[3] == '8' && (b[4] == '7' || b[4] == '9') && b[5] == 'a') {
            return "image/gif";
        }
        if (b[0] == 'R' && b[1] == 'I' && b[2] == 'F' && b[3] == 'F'
                && b[8] == 'W' && b[9] == 'E' && b[10] == 'B' && b[11] == 'P') {
            return "image/webp";
        }
        return null;
    }
}
